"""Размеры и классы раскладки — в одном месте на все вкладки.

Вкладки устроены одинаково: слева холст во всю доступную высоту, справа
панель настроек. Пока высоты стояли числами прямо в вызовах компонентов
(620 у результата, 620 у редактора, 560 у галереи), они расходились между
вкладками и не зависели от окна вовсе: на ноутбуке холст не помещался, на
большом мониторе под ним оставалась пустота.

Высоты заданы выражениями CSS, а не числами: Gradio принимает строку и
понимает её как длину в единицах CSS (см. докстроку ``height`` у
``gr.Gallery``). ``clamp`` даёт нижнюю границу, за которой холст перестаёт
быть рабочим, верхнюю, за которой картинка тонет в пустоте, и между ними —
остаток высоты окна.

Классы нужны файлу стилей для того, чего параметрами не выразить:
переносов по ширине окна и сжатия нескольких громоздких элементов.
Держатся они здесь, а не строками по вкладкам, чтобы опечатка в имени не
разрывала связь с CSS молча — на совпадение есть тест.
"""

from __future__ import annotations

# Вычитаемое — это шапка, полоса вкладок, строка промта и отступы: всё, что
# на экране стоит выше холста и ниже его. Подобрано так, чтобы на экране
# 1080p холст занимал остаток высоты без полосы прокрутки страницы.
#
# Верхняя граница поднята с 60rem: на мониторе 4K окно высотой 2160 px, и
# холст, упёршийся в 960, оставлял под собой пустое поле в половину экрана.
CANVAS_HEIGHT = "clamp(20rem, calc(100vh - 25rem), 110rem)"

# Галерея на своей вкладке: над ней только шапка и вкладки, поэтому остаток
# больше.
BROWSE_HEIGHT = "clamp(20rem, calc(100vh - 17rem), 120rem)"

# Результат правки на широком экране стоит рядом с редактором и повторяет
# его высоту; на узком уезжает под него, и там высота своя — меньше, иначе
# страница растянулась бы на два экрана (задаётся в style.css).
PREVIEW_HEIGHT = CANVAS_HEIGHT

# Лента референсов: одна строка миниатюр с подписями.
STRIP_HEIGHT = "clamp(7.5rem, 15vh, 12rem)"

# Минимальная ширина, ниже которой панель настроек нечитаема; по ней же
# Gradio решает, переносить ли колонку на следующую строку.
SIDE_MIN_WIDTH = 340
CANVAS_MIN_WIDTH = 480

# Классы для style.css.
# Переключатель языка висит в правом верхнем углу поверх полосы вкладок и
# не занимает собственной высоты: отдельная строка ради двух букв — роскошь,
# которой заголовок уже обошёлся.
LANG = "qs-lang"
WORK_ROW = "qs-work"
PROMPT_BAR = "qs-bar"
DROP_ZONE = "qs-drop"
STATUS = "qs-status"

# Две роли колонок рабочей строки. Раньше их задавал ``scale`` — 3 к 1, — и
# на широком мониторе вместе с холстом растягивалась панель настроек: на 4K
# она выходила в 822 px, где поля ввода и подписи тонут в пустоте. Ширина
# полезна холсту, а не форме, поэтому холст теперь тянется, а панель держит
# свою ширину.
CANVAS_COL = "qs-canvas"
SIDE_COL = "qs-side"

# Строка из двух холстов: редактор и результат. На широком экране они стоят
# рядом, на узком встают друг под друга.
BOARDS_ROW = "qs-boards"
PREVIEW = "qs-preview"

# Сам холст — картинка или редактор. Класс нужен ради нижней границы высоты:
# параметр ``height`` Gradio задаёт высоту содержимого, и пустой компонент
# схлопывается в полоску. На мониторе 4K пустая галерея результата занимала
# 238 px вместо 1760, а остальные три четверти экрана пустовали.
BOARD = "qs-board"
BROWSE = "qs-browse"

# Колонки вкладки настроек. Форму растягивать некуда: строка ввода в три
# тысячи пикселей не читается, а выглядит как недосмотр.
FORM_COL = "qs-form"

# Колонка с длинным текстом — системный промт. Ей ширина нужна: править
# абзацы в полосе шириной с телефон неудобно. Но и расти без предела ей
# незачем — строка в две тысячи пикселей теряет начало, пока глаз идёт к
# концу, поэтому у колонки есть потолок.
TEXT_COL = "qs-text"

# Само поле системного промта. Высота у него не по числу строк, а по окну:
# восемнадцать строк — это компромисс для ноутбука, а на большом мониторе
# под полем оставалось пустое поле в половину экрана.
LONG_TEXT = "qs-longtext"
