"""Веб-интерфейс на Gradio. Вычислений здесь нет — только сборка и связывание."""

import os

# Оболочка локальная и никуда не звонит. Без этой строки каждый ``gr.Blocks``
# без явного ``analytics_enabled=False`` запускает поток, который спрашивает
# у api.gradio.app свежую версию Gradio: лишний сетевой запрос с машины
# пользователя, а в тестах — «Logging error: I/O operation on closed file»,
# когда поток пишет в журнал после того, как pytest закрыл перехваченный
# вывод. Задаётся здесь, до первого импорта gradio в пакете, и потому
# действует на приложение, тесты и инструменты разом; явная настройка
# пользователя в окружении сохраняется.
os.environ.setdefault("GRADIO_ANALYTICS_ENABLED", "False")
