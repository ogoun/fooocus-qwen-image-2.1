"""Имена классов раскладки — одно место на все вкладки.

Размеры здесь больше не живут. Раньше высоты задавались строками CSS в
параметре ``height`` компонента, и получалось, что высота холста зависит
только от окна: при узкой колонке картинка сжималась, а поле вокруг неё
оставалось прежним — изображение тонуло в пустоте. Высота обязана зависеть
и от ширины, а такое выражается пропорцией (``aspect-ratio``), то есть
средствами CSS, а не числом в Python.

Поэтому в ``ui/style.css`` — вся геометрия: переменные, пропорции, потолки
и пороги переносов. Здесь — только имена классов, по которым правила
находят свои компоненты, и минимальные ширины: их Gradio принимает числом и
учитывает при переносе колонок.

Опечатка в имени ничего не сломает на запуске — Gradio повесит класс,
которого нет в стилях, браузер пропустит правило, которому не на чем
сработать, а интерфейс просто поедет. Поэтому связь проверяется тестом
(``tests/test_layout.py``) в обе стороны.
"""

from __future__ import annotations

# Минимальные ширины: ниже них колонка нечитаема, и по ним же Gradio решает,
# переносить ли её на следующую строку.
SIDE_MIN_WIDTH = 340
CANVAS_MIN_WIDTH = 480

# --- роли колонок --------------------------------------------------------
# Холст тянется, панель настроек держит свою ширину: место идёт картинке, а
# не форме. Подробности — в style.css рядом с правилами.
CANVAS_COL = "qs-canvas"
SIDE_COL = "qs-side"
# Колонка сетки референсов — слева от холста результата.
REFS_COL = "qs-refs"

# Колонки вкладки настроек: короткая форма и колонка с длинным текстом.
FORM_COL = "qs-form"
TEXT_COL = "qs-text"
LONG_TEXT = "qs-longtext"

# --- холсты и ленты ------------------------------------------------------
# Холст с изображением: редактор, результат генерации, результат правки.
BOARD = "qs-board"
# Сетка галереи: это список, а не один кадр, и высота у неё по окну.
BROWSE = "qs-browse"
# Слот референса: квадратная ячейка сетки два на пять.
REF_SLOT = "qs-refslot"
# Результат правки: тот же холст, но на узком экране он под редактором и
# занимает меньше места.
PREVIEW = "qs-preview"
# Кисть маски: её разметка живёт в собственном теневом корне, а снаружи
# узлу компонента нужно только одно — занять весь холст.
PAINTER = "qs-painter"

# --- строки и группы -----------------------------------------------------
WORK_ROW = "qs-work"
BOARDS_ROW = "qs-boards"

# Места на вкладке правки. На широком экране кисть и результат стоят рядом, а
# промт под ними; на узком всё встаёт в столбец, и порядок обязан быть
# «кисть → промт → действия → результат»: главное действие не должно
# уезжать за нижний край экрана из-за поля результата, которое нужно только
# после нажатия.
SLOT_EDITOR = "qs-slot-editor"
SLOT_PROMPT = "qs-slot-prompt"
SLOT_ACTIONS = "qs-slot-actions"
SLOT_RESULT = "qs-slot-result"

# Кнопки в углу галерей. Без «share»: она публикует картинку в обсуждения
# Hugging Face Spaces и работает только там — у локального приложения ей
# некуда отправлять, и нажатие кончалось ошибкой.
GALLERY_BUTTONS: list[str] = ["download", "fullscreen"]
PROMPT_BAR = "qs-bar"
STATUS = "qs-status"
# Переключатель языка висит в правом верхнем углу поверх полосы вкладок.
LANG = "qs-lang"

# Карточка выбранной картинки в галерее: промт и параметры — текстом.
CARD = "qs-card"

# --- вкладки -------------------------------------------------------------
# Имена, по которым действия переключают вкладку сами: «Повторить
# параметры» уводит на генерацию, «Открыть в редакторе» — на правку.
TAB_GENERATE = "generate"
TAB_EDIT = "edit"
TAB_GALLERY = "gallery"
TAB_SETTINGS = "settings"
